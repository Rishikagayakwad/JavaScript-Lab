let mood = "happy";

switch (mood) {

    case "happy":
        console.log(" Keep smiling!");
        break;

    case "sad":
        console.log(" It's okay to feel sad.");
        break;

    case "angry":
        console.log(" Take a deep breath.");
        break;

    case "tired":
        console.log(" Get some rest.");
        break;

    default:
        console.log(" Have a good day!");
}